#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
output_dir="${DOTFILES_PACKAGE_INVENTORY_DIR:-$repo_root/packages/ubuntu}"
temporary_files=()
export LC_ALL=C
export DOTNET_NOLOGO=1
export DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1

usage() {
	cat <<'USAGE'
Usage: scripts/export-installed-apps.sh [--output-dir DIR]

Export installed Ubuntu package and developer-tool inventories.

The output is a machine snapshot for review and portability. It is not used
automatically by setup.sh, whose curated package lists remain the normal
bootstrap path.
USAGE
}

cleanup() {
	local path
	for path in "${temporary_files[@]}"; do
		rm -f -- "$path"
	done
}
trap cleanup EXIT

while (($# > 0)); do
	case "$1" in
	--output-dir)
		(($# >= 2)) || { printf 'missing value for --output-dir\n' >&2; exit 2; }
		output_dir="$2"
		shift 2
		;;
	--help | -h)
		usage
		exit 0
		;;
	*)
		printf 'unknown option: %s\n' "$1" >&2
		usage >&2
		exit 2
		;;
	esac
done

mkdir -p "$output_dir"

write_inventory() {
	local filename="$1"
	local description="$2"
	local producer="$3"
	local temporary
	local entries
	local failed=false
	if ! entries="$("$producer")"; then
		entries=''
		failed=true
		printf 'warning: %s export unavailable or failed\n' "$filename" >&2
	fi

	temporary="$(mktemp "$output_dir/.${filename}.XXXXXX")"
	temporary_files+=("$temporary")
	{
		printf '# Generated by scripts/export-installed-apps.sh; review before restoring.\n'
		printf '# %s\n' "$description"
		printf '# Names are intentionally unpinned unless the source includes a channel or remote.\n'
		printf '\n'
		if [[ "$failed" == true ]]; then
			printf '# The source command was unavailable or failed; no entries were exported.\n'
		else
			printf '%s\n' "$entries"
		fi
	} | sed '/^[[:space:]]*$/d' >"$temporary"

	{
		head -n 3 "$temporary"
		tail -n +4 "$temporary" | sort -u
	} >"$temporary.sorted"
	temporary_files+=("$temporary.sorted")
	mv -- "$temporary.sorted" "$output_dir/$filename"
	rm -f -- "$temporary"
}

apt_inventory() {
	if command -v apt-mark >/dev/null 2>&1; then
		apt-mark showmanual
	else
		printf 'warning: apt-mark is unavailable; apt inventory is empty\n' >&2
		return 1
	fi
}

snap_inventory() {
	local snap_output

	if command -v snap >/dev/null 2>&1; then
		if command -v timeout >/dev/null 2>&1; then
			if ! snap_output="$(timeout 10s snap list 2>/dev/null)"; then
				printf 'warning: snap list failed or timed out; snap inventory is empty\n' >&2
				return 1
			fi
		else
			snap_output="$(snap list 2>/dev/null)" || {
				printf 'warning: snap list failed; snap inventory is empty\n' >&2
				return 1
			}
		fi
		printf '%s\n' "$snap_output" | awk 'NR > 1 && NF >= 4 { print $1 "\t" $4 }'
	else
		printf 'warning: snap is unavailable; snap inventory is empty\n' >&2
		return 1
	fi
}

flatpak_inventory() {
	if command -v flatpak >/dev/null 2>&1; then
		flatpak list --app --columns=application,origin
	else
		printf 'warning: flatpak is unavailable; flatpak inventory is empty\n' >&2
		return 1
	fi
}

npm_inventory() {
	if ! command -v npm >/dev/null 2>&1 || ! command -v node >/dev/null 2>&1; then
		printf 'warning: npm or node is unavailable; npm inventory is empty\n' >&2
		return 1
	fi
	npm list --global --depth=0 --json 2>/dev/null |
		node -e 'const fs = require("fs"); const data = JSON.parse(fs.readFileSync(0, "utf8")); for (const name of Object.keys(data.dependencies || {}).sort()) console.log(name);'
}

pipx_inventory() {
	if command -v pipx >/dev/null 2>&1; then
		pipx list --short | awk 'NF { print $1 }'
	else
		printf 'warning: pipx is unavailable; pipx inventory is empty\n' >&2
		return 1
	fi
}

cargo_inventory() {
	if command -v cargo >/dev/null 2>&1; then
		cargo install --list | awk '/^[^[:space:]]/ { sub(/[[:space:]].*/, ""); print }'
	else
		printf 'warning: cargo is unavailable; cargo inventory is empty\n' >&2
		return 1
	fi
}

dotnet_inventory() {
	if command -v dotnet >/dev/null 2>&1; then
		dotnet tool list --global 2>/dev/null |
			awk '/^-+[[:space:]]*$/ { entries=1; next } entries && NF >= 3 { print $1 }'
	else
		printf 'warning: dotnet is unavailable; dotnet inventory is empty\n' >&2
		return 1
	fi
}

write_inventory apt-manual.txt 'APT packages marked as manually installed.' apt_inventory
write_inventory snap.tsv 'Snap names and their tracked channels.' snap_inventory
write_inventory flatpak.tsv 'Flatpak application IDs and configured remotes.' flatpak_inventory
write_inventory npm-global.txt 'Global npm package names.' npm_inventory
write_inventory pipx.txt 'pipx application names.' pipx_inventory
write_inventory cargo.txt 'Cargo-installed package names.' cargo_inventory
write_inventory dotnet-tools.txt 'Globally installed .NET tool package IDs.' dotnet_inventory

printf 'exported installed-app inventories to %s\n' "$output_dir"
